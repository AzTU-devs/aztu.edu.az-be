insert into about_page_tr (page_id, lang_code, title, councils_title, links_title, created_at)
select p.id, 'az', 'Elmi Şura', 'Şuralar', 'Bölmədə daha çox', current_timestamp
from about_pages p where p.page_key = 'scientific-board'
on conflict (page_id, lang_code) do nothing;

insert into about_page_tr (page_id, lang_code, title, councils_title, links_title, created_at)
select p.id, 'en', 'Scientific Board', 'Councils', 'More in this section', current_timestamp
from about_pages p where p.page_key = 'scientific-board'
on conflict (page_id, lang_code) do nothing;


